import type {
  DocumentContent,
  DocumentDescriptor,
  DocumentField,
  DocumentSection,
  DocumentTable,
} from '@/types/document';
import type { InvestorIdentity } from '@/types/investor';
import { HOLDING_SOURCE_LABEL, HOLDING_SOURCE_PROVENANCE } from '@/types/portfolio';
import { formatCurrency, formatPercentage, formatTenure } from '@/utils';
import { formatMaturityDate } from '@/utils/finance';
import {
  MATURITY_INSTRUCTION_LABEL,
  type MaturityEntry,
  type MaturitySchedule,
} from '@/utils/portfolio';
import type { PortfolioSummary } from '@/utils/portfolio';

/**
 * What is printed on a document.
 *
 * ## Every value on this sheet is already true elsewhere
 *
 * Nothing is computed here. Principal, rate and tenure are read from the
 * holding; maturity date, expected interest and maturity value come from
 * `summarisePortfolio`; the schedule position and the outlook sentence come
 * from `buildMaturitySchedule`. This file **formats an existing answer** — it
 * never derives a second one, which is what keeps a statement from disagreeing
 * with the dashboard that produced it.
 *
 * ## An absent figure stays absent
 *
 * `DocumentField.value` is `null` where the platform genuinely holds nothing,
 * and the row says so with the reason beside it. The temptation a document
 * creates is to fill the gaps — a default instruction, an approximated date for
 * a term published in days — and every one of those would be the platform
 * inventing a fact about somebody's money.
 *
 * ## It is not a bank certificate, and it says so
 *
 * Each document carries its provenance in the notes at the foot, in the
 * customer's words. A platform-derived statement that omitted that line would
 * be indistinguishable from an official document at the moment it is printed,
 * which is precisely when the distinction matters.
 *
 * Pure and React-free; the caller supplies the identity and the clock.
 */

const NOT_RECORDED = 'Not recorded';

/** How the platform describes itself on every document it produces. */
const PLATFORM_NOTE =
  'This document was generated by the FD Investment Platform from your own booking and portfolio records. It is not a bank certificate and is not issued by the bank.';

/** Said wherever a figure is expected rather than settled. */
const DERIVED_NOTE =
  'Expected figures are calculated from the terms of your deposit. Final amounts are confirmed by the bank at maturity.';

const DEMO_NOTE =
  'Demonstration build: no bank document system is connected, and nothing on this page has been filed with or sent to a bank.';

/** "27 Aug 2026, 14:32" — enough to identify one generation of a document. */
function formatTimestamp(at: number): string {
  return new Intl.DateTimeFormat('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(at));
}

/**
 * The term, or an honest statement that the platform holds no month count.
 *
 * A holding records whole months, and `0` is what a deposit priced in days
 * leaves behind. The day count itself lives in the catalogue product, not in
 * the deposit the investor owns, so this says what is missing rather than
 * converting 91 days into "3 months" — a conversion this platform refuses to
 * make anywhere.
 */
function tenureField(tenureMonths: number): DocumentField {
  return tenureMonths > 0
    ? { label: 'Tenure', value: formatTenure(tenureMonths) }
    : {
        label: 'Tenure',
        value: null,
        hint: 'The bank publishes this deposit’s term in days, so no month count is recorded.',
      };
}

function maturityDateField(entry: MaturityEntry): DocumentField {
  return entry.view.maturesOn === null
    ? {
        label: 'Maturity date',
        value: null,
        hint: 'No maturity date is available for a term published in days.',
      }
    : { label: 'Maturity date', value: formatMaturityDate(entry.view.maturesOn) };
}

function instructionField(entry: MaturityEntry): DocumentField {
  return entry.instruction === null
    ? {
        label: 'Maturity instruction',
        value: null,
        hint: 'The bank’s application form did not record an instruction for this deposit.',
      }
    : { label: 'Maturity instruction', value: MATURITY_INSTRUCTION_LABEL[entry.instruction] };
}

/** What the schedule says about where the deposit is — never about settlement. */
const STAGE_LABEL: Record<MaturityEntry['stage'], string> = {
  scheduled: 'Running',
  'maturing-soon': 'Maturing soon',
  matured: 'Term ended',
  undated: 'Running — no maturity date recorded',
};

/**
 * Who the document is for.
 *
 * Read from the investor record, never copied into one. The PAN is the masked
 * form and nothing else exists on the platform to print — a document is not a
 * reason to start holding a full identifier.
 */
function issuedTo(identity: InvestorIdentity | null): DocumentField[] {
  return [
    { label: 'Investor', value: identity?.profile.fullName ?? null, hint: NOT_RECORDED },
    { label: 'PAN', value: identity?.pan.masked ?? null, hint: NOT_RECORDED },
  ];
}

function depositSection(entry: MaturityEntry): DocumentSection {
  const { holding } = entry.view;

  return {
    id: 'deposit',
    title: 'Deposit',
    fields: [
      { label: 'Bank', value: holding.bank.name },
      { label: 'Product', value: holding.productName },
      { label: 'Reference', value: holding.reference },
      {
        label: 'Source',
        value: HOLDING_SOURCE_LABEL[holding.source],
        hint: HOLDING_SOURCE_PROVENANCE[holding.source],
      },
      { label: 'Status', value: STAGE_LABEL[entry.stage] },
    ],
  };
}

function investmentSection(entry: MaturityEntry): DocumentSection {
  const { holding } = entry.view;

  return {
    id: 'investment',
    title: 'Investment',
    fields: [
      { label: 'Amount invested', value: formatCurrency(holding.principal) },
      { label: 'Interest rate', value: `${formatPercentage(holding.annualRate)} per annum` },
      tenureField(holding.tenureMonths),
      {
        label: 'Interest payout',
        value: holding.isCumulative ? 'Compounded, paid at maturity' : holding.payoutLabel,
      },
      { label: 'Start date', value: formatMaturityDate(new Date(holding.startedAt)) },
    ],
  };
}

function maturitySection(entry: MaturityEntry): DocumentSection {
  return {
    id: 'maturity',
    title: 'Maturity',
    fields: [
      maturityDateField(entry),
      { label: 'Expected interest', value: formatCurrency(entry.view.totalInterest) },
      { label: 'Expected maturity amount', value: formatCurrency(entry.view.maturityValue) },
      instructionField(entry),
    ],
  };
}

function documentSection(descriptor: DocumentDescriptor): DocumentSection {
  const { availability } = descriptor;

  return {
    id: 'document',
    title: 'Document',
    fields: [
      { label: 'Document', value: descriptor.title },
      {
        label: 'Issued by',
        value:
          descriptor.issuer === 'platform'
            ? 'FD Investment Platform (platform-generated)'
            : 'The bank',
      },
      {
        label: 'Generated',
        value:
          availability.status === 'available' ? formatTimestamp(availability.generatedAt) : null,
        hint: availability.status === 'unavailable' ? availability.reason : undefined,
      },
    ],
  };
}

export interface DocumentInputs {
  descriptor: DocumentDescriptor;
  summary: PortfolioSummary;
  schedule: MaturitySchedule;
  identity: InvestorIdentity | null;
}

/** Every deposit with a schedule position, in the catalogue's own order. */
function scheduleEntries(schedule: MaturitySchedule): MaturityEntry[] {
  return [...schedule.upcoming, ...schedule.matured, ...schedule.undated];
}

function findEntry(schedule: MaturitySchedule, reference: string): MaturityEntry | undefined {
  return scheduleEntries(schedule).find((entry) => entry.view.holding.reference === reference);
}

function portfolioTable(schedule: MaturitySchedule, summary: PortfolioSummary): DocumentTable {
  const entries = scheduleEntries(schedule);

  return {
    columns: ['Bank', 'Reference', 'Invested', 'Rate', 'Matures', 'Expected value'],
    rows: entries.map((entry) => [
      entry.view.holding.bank.name,
      entry.view.holding.reference,
      formatCurrency(entry.view.holding.principal),
      formatPercentage(entry.view.holding.annualRate),
      entry.view.maturesOn === null ? NOT_RECORDED : formatMaturityDate(entry.view.maturesOn),
      formatCurrency(entry.view.maturityValue),
    ]),
    /*
      Only the columns that can honestly be totalled. Averaging a rate across
      deposits of different sizes would produce a number that is true of no
      deposit the investor holds, so that cell stays empty.
    */
    totals: [
      `${String(entries.length)} ${entries.length === 1 ? 'deposit' : 'deposits'}`,
      '',
      formatCurrency(summary.totalPrincipal),
      '',
      '',
      formatCurrency(summary.totalMaturityValue),
    ],
  };
}

/**
 * The sheet for one descriptor, or `null` when this investor has no such
 * document — an unknown reference, or a document the platform cannot produce.
 */
export function buildDocumentContent({
  descriptor,
  summary,
  schedule,
  identity,
}: DocumentInputs): DocumentContent | null {
  if (descriptor.availability.status !== 'available') return null;

  const base = {
    descriptor,
    issuedTo: issuedTo(identity),
    table: null as DocumentTable | null,
  };

  if (descriptor.kind === 'portfolio-statement') {
    return {
      ...base,
      table: portfolioTable(schedule, summary),
      sections: [
        documentSection(descriptor),
        {
          id: 'totals',
          title: 'Totals',
          fields: [
            { label: 'Deposits held', value: String(summary.activeCount) },
            { label: 'Total invested', value: formatCurrency(summary.totalPrincipal) },
            {
              label: 'Expected interest',
              value: formatCurrency(summary.totalInterest),
              hint: 'Across every deposit, over its full term.',
            },
            {
              label: 'Expected maturity value',
              value: formatCurrency(summary.totalMaturityValue),
            },
          ],
        },
      ],
      notes: [PLATFORM_NOTE, DERIVED_NOTE, DEMO_NOTE],
    };
  }

  const entry = findEntry(schedule, descriptor.subject.id);
  if (entry === undefined) return null;

  if (descriptor.kind === 'booking-confirmation') {
    const { holding } = entry.view;

    return {
      ...base,
      sections: [
        documentSection(descriptor),
        depositSection(entry),
        {
          id: 'booking',
          title: 'Booking',
          fields: [
            { label: 'Reference', value: holding.reference },
            { label: 'Amount invested', value: formatCurrency(holding.principal) },
            { label: 'Interest rate', value: `${formatPercentage(holding.annualRate)} per annum` },
            tenureField(holding.tenureMonths),
            {
              label: 'Recorded as started',
              value: formatMaturityDate(new Date(holding.startedAt)),
              hint: 'The date the platform recorded this deposit as beginning.',
            },
          ],
        },
      ],
      notes: [
        'This is the platform’s record of your booking. The bank’s own confirmation of the deposit is a separate document, issued by the bank.',
        PLATFORM_NOTE,
        DEMO_NOTE,
      ],
    };
  }

  if (descriptor.kind === 'maturity-advice') {
    return {
      ...base,
      sections: [
        documentSection(descriptor),
        depositSection(entry),
        {
          id: 'maturity',
          title: 'Maturity',
          fields: [
            maturityDateField(entry),
            {
              label: 'Days remaining',
              value:
                entry.daysRemaining === null || entry.daysRemaining < 0
                  ? null
                  : String(entry.daysRemaining),
              hint:
                entry.daysRemaining !== null && entry.daysRemaining < 0
                  ? 'The maturity date has passed.'
                  : undefined,
            },
            { label: 'Expected maturity amount', value: formatCurrency(entry.view.maturityValue) },
            instructionField(entry),
          ],
        },
        {
          id: 'outlook',
          title: 'What happens next',
          fields: [{ label: '', value: entry.outlook }],
        },
      ],
      notes: [PLATFORM_NOTE, DERIVED_NOTE, DEMO_NOTE],
    };
  }

  /* `fd-statement` — the full picture of one deposit. */
  return {
    ...base,
    sections: [
      documentSection(descriptor),
      depositSection(entry),
      investmentSection(entry),
      maturitySection(entry),
    ],
    notes: [PLATFORM_NOTE, DERIVED_NOTE, DEMO_NOTE],
  };
}

export { NOT_RECORDED, PLATFORM_NOTE, STAGE_LABEL };
