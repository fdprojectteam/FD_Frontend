import type { ReactNode } from 'react';

import { cn } from '@/lib/utils';

/**
 * PreferenceField — the label / control / message shell every Investment
 * Preference wears (change request, 2026-08-02).
 *
 * **Why a shell rather than one component per field.** The brief names four
 * preferences still to come — Tenure, Interest Payout, Senior Citizen, Tax Saver
 * — and they share nothing except a control. What they *do* share is the part
 * that is easy to get subtly wrong and invisible when you do: the `htmlFor` /
 * `id` pairing, where the error sits relative to the input, and whether the
 * message is announced or merely coloured. Written once here, a field added in
 * six months inherits all of it; written per field, the fourth one quietly ships
 * with a label that is not associated with anything.
 *
 * **It renders its control through a callback**, not as free `children`, because
 * the id is generated by the section and the control must receive it. Handing
 * the child the ids it has to bind makes the association impossible to omit —
 * the alternative, trusting each call site to repeat the right `id` and
 * `aria-describedby` string, is the same class of duplication the design tokens
 * rule exists to prevent.
 *
 * **Presentation-only** (I3). It holds no state, validates nothing, and decides
 * nothing about what a valid preference is. `CompareScreen` owns the rules, as
 * it owns every other rule on this route.
 */
export interface PreferenceFieldProps {
  /** Stable id for the control; the label and message are derived from it. */
  id: string;
  label: string;
  /** Static guidance shown when there is no error. */
  hint?: string;
  /** Validation message; when present it replaces the hint and is announced. */
  error?: string | null;
  className?: string;
  /**
   * Renders the control. Receives the ids it must bind, so the association
   * cannot be forgotten at the call site.
   */
  children: (ids: { id: string; describedBy: string | undefined }) => ReactNode;
}

export function PreferenceField({
  id,
  label,
  hint,
  error = null,
  className,
  children,
}: PreferenceFieldProps) {
  const messageId = `${id}-message`;
  const message = error ?? hint ?? null;

  return (
    <div className={cn('flex flex-col gap-1.5', className)}>
      <label htmlFor={id} className="text-caption text-content-muted font-medium">
        {label}
      </label>

      {children({ id, describedBy: message ? messageId : undefined })}

      {/*
        One element for both states, so the field cannot grow a second line when
        an error appears over a hint — and `role="alert"` only when there is
        something urgent to announce. A permanently-live region would re-announce
        the static hint on every keystroke that re-rendered it.
      */}
      {message ? (
        <p
          id={messageId}
          role={error ? 'alert' : undefined}
          className={cn('text-caption', error ? 'text-error' : 'text-content-muted')}
        >
          {message}
        </p>
      ) : null}
    </div>
  );
}
